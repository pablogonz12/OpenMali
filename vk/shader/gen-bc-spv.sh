#!/bin/bash
# SPDX-License-Identifier: MIT
# R4-M7: bc{6h,7}.comp.in -> bc{6h,7}.comp (tables from Mesa's texcompress_bptc_tmp.h), then GLSL -> SPIR-V for bc{1,4,6h,7}.comp + etc2.comp and
# src/mali_bc_spv.h (committed; the driver embeds the SPIR-V). Usage: gen-bc-spv.sh [mesa dir, default ../../third_party/mesa]
set -e; cd "$(dirname "$0")"
M=${1:-../../third_party/mesa}
python3 -I gen-bc-tables.py $M/src/util/format/texcompress_bptc_tmp.h .
H=../src/mali_bc_spv.h
echo "/* SPDX-License-Identifier: MIT. GENERATED by shader/gen-bc-spv.sh from shader/bc*.comp, do not edit. */" > $H
for s in bc1 bc4 bc6h bc7 etc2; do
   glslangValidator -V --target-env vulkan1.1 $s.comp -o $s.comp.spv >/dev/null
   spirv-val $s.comp.spv
   echo "static const uint32_t ${s}_spv[] = {" >> $H
   od -An -v -tx4 -w16 $s.comp.spv | sed -E 's/ ([0-9a-f]{8})/0x\1,/g' >> $H
   echo "};" >> $H
done
# hardware probe -> tests/t_bc_probe_spv.h
H=../tests/t_bc_probe_spv.h
echo "/* SPDX-License-Identifier: MIT. GENERATED by shader/gen-bc-spv.sh from shader/bc_probe.comp, do not edit. */" > $H
glslangValidator -V --target-env vulkan1.1 bc_probe.comp -o bc_probe.comp.spv >/dev/null
spirv-val bc_probe.comp.spv
echo "static const uint32_t bc_probe_spv[] = {" >> $H
od -An -v -tx4 -w16 bc_probe.comp.spv | sed -E 's/ ([0-9a-f]{8})/0x\1,/g' >> $H
echo "};" >> $H
