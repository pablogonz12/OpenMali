# Specialised loadOp LOAD shaders (preload_fast.frag, preload_zs_fast.frag) -> src/mali_preload_fast_spv.h (committed).
# Kept apart from gen-meta-spv.sh so the general preload shaders' SPIR-V (mali_preload_spv.h) stays byte-identical.
# Array names: preload_fast_<fmt>[_srgb][_ms]_frag_spv, preload_zsf_<z32|z16|z24>[_s][_ms]_frag_spv (mali_meta.c slots).
set -e; cd "$(dirname "$0")"
H=../src/mali_preload_fast_spv.h
echo "/* SPDX-License-Identifier: MIT. GENERATED by shader/gen-preload-fast-spv.sh from shader/preload_fast.frag and shader/preload_zs_fast.frag, do not edit. */" > $H
emit() { # name source defines...
   local n=$1 s=$2; shift 2
   glslangValidator -V --target-env vulkan1.1 "$@" $s -o $n.spv >/dev/null
   spirv-val $n.spv
   echo "static const uint32_t ${n}_spv[] = {" >> $H
   od -An -v -tx4 -w16 $n.spv | sed -E 's/ ([0-9a-f]{8})/0x\1,/g' >> $H
   echo "};" >> $H
}
for ms in "" _ms; do
   md=; [ -n "$ms" ] && md=-DOUT_SAMPLE
   for f in rgba8:FMT_RGBA8 bgra8:FMT_BGRA8 a2b10:FMT_A2B10G10R10 a2r10:FMT_A2R10G10B10; do
      emit preload_fast_${f%%:*}${ms}_frag preload_fast.frag -D${f#*:} $md
      case $f in rgba8*|bgra8*) emit preload_fast_${f%%:*}_srgb${ms}_frag preload_fast.frag -D${f#*:} -DSRGB $md ;; esac
   done
   for z in z32:Z32 z16:Z16 z24:Z24; do
      emit preload_zsf_${z%%:*}${ms}_frag preload_zs_fast.frag -D${z#*:} $md
      emit preload_zsf_${z%%:*}_s${ms}_frag preload_zs_fast.frag -D${z#*:} -DDO_S $md
   done
done
