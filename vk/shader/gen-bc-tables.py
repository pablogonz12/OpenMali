# R4-M7: fills the table markers of bc6h.comp.in / bc7.comp.in from Mesa's util/format/texcompress_bptc_tmp.h (partition tables,
# anchor indices, BC6H mode bitfields, BC7 mode parameters) and writes bc6h.comp / bc7.comp. Usage: gen-bc-tables.py <bptc_tmp.h> <shader dir>
import re, sys, os

src = open(sys.argv[1]).read()
sd = sys.argv[2]

def block(name):
    i = src.index(name)
    j = src.index('{', src.index('=', i))
    depth, k = 0, j
    while True:
        if src[k] == '{': depth += 1
        elif src[k] == '}':
            depth -= 1
            if depth == 0: break
        k += 1
    return src[j:k + 1]

def parse(txt):
    txt = re.sub(r'/\*.*?\*/', '', txt, flags=re.S).replace('true', '1').replace('false', '0')
    toks = re.findall(r'\{|\}|-?\w+', txt)
    pos = 0
    def rec():
        nonlocal pos
        assert toks[pos] == '{'; pos += 1
        out = []
        while toks[pos] != '}':
            if toks[pos] == '{': out.append(rec())
            else: out.append(int(toks[pos].rstrip('uU'), 0)); pos += 1
        pos += 1
        return out
    return rec()

def arr(name, vals, per=8):
    lines = []
    for i in range(0, len(vals), per):
        lines.append('   ' + ', '.join('0x%08xu' % v for v in vals[i:i + per]) + ',')
    return 'const uint %s[%d] = uint[](\n%s\n);' % (name, len(vals), '\n'.join(lines).rstrip(','))

p1 = parse(block('partition_table1'))
p2 = parse(block('partition_table2'))
anch = parse(block('anchor_indices'))
fm = parse(block('bptc_float_modes'))
um = parse(block('bptc_unorm_modes'))
assert len(p1) == 64 and len(p2) == 64 and len(anch) == 3 and len(fm) == 18 and len(um) == 8

# BC7 mode word: nsub | pbits<<2 | rot<<5 | isel<<6 | ncol<<7 | nalpha<<11 | epbit<<15 | shbit<<16 | nidx<<17 | nsec<<20
u7 = []
for m in um:
    ns, pb, rot, isel, nc, na, ep, sh, ni, nsec = m
    u7.append(ns | pb << 2 | rot << 5 | isel << 6 | nc << 7 | na << 11 | ep << 15 | sh << 16 | ni << 17 | nsec << 20)
tab7 = [arr('PART2', p1), arr('PART3', p2),
        arr('ANCH2', anch[0]),
        arr('ANCH3A', anch[1]), arr('ANCH3B', anch[2]), arr('MODES', u7)]

# BC6H mode info: reserved | transformed<<1 | partbits<<2 | nend<<5 | nidx<<10 | d0<<13 | d1<<17 | d2<<21
info, fld = [], []
for m in fm:
    if m[0] == 1 and len(m) == 1:
        info.append(1); fld += [0] * 24; continue
    res, tr, pb, ne, ni, dl, bf = m
    info.append(res | tr << 1 | pb << 2 | ne << 5 | ni << 10 | dl[0] << 13 | dl[1] << 17 | dl[2] << 21)
    row = []
    for b in bf:
        if b[0] == -1: break
        # endpoint | comp<<2 | offset<<4 | nbits<<8 | reverse<<12
        row.append(b[0] | b[1] << 2 | b[2] << 4 | b[3] << 8 | b[4] << 12)
    assert len(row) <= 23
    fld += row + [0] * (24 - len(row))
tab6 = [arr('PART2', p1), arr('ANCH2', anch[0]), arr('MINFO', info), arr('MFLD', fld)]

for name, tabs in (('bc6h', tab6), ('bc7', tab7)):
    t = open(os.path.join(sd, name + '.comp.in')).read()
    t = t.replace('//@TABLES@', '// ---- generated by gen-bc-tables.py from Mesa texcompress_bptc_tmp.h ----\n' + '\n'.join(tabs) + '\n// ---- end generated ----')
    t = t.replace('//@HEADER@', '// GENERATED from %s.comp.in by gen-bc-tables.py: do not edit.' % name)
    open(os.path.join(sd, name + '.comp'), 'w').write(t)
