// Prints the ASTC decoder LUTs (Mesa's texcompress_astc_luts.cpp, from Granite) as GLSL const arrays for astc.comp.in (gen-bc-spv.sh).
#include <cstdio>
#include "texcompress_astc_luts.h"

// Concatenated into one uint table (the shader reads it from a storage buffer: private const arrays spill to 166 KB of TLS per thread).
static unsigned g_tab[8192], g_n;
static bool g_c;
template <class T> static void dump(const char *n, const T *v, size_t c)
{
   if (!g_c) printf("#define OFF_%s %uu\n", n, g_n);
   for (size_t i = 0; i < c; i++) g_tab[g_n++] = (unsigned)v[i];
}

int main(int argc, char **argv)
{
   g_c = argc > 1 && argv[1][0] == 'c';   // "c": the table as a C array (driver), otherwise the offsets as GLSL defines (astc.comp)
   auto &l = Granite::get_astc_luts();
   dump("CE", &l.color_endpoint.lut[0][0][0], 9 * 128 * 4);
   dump("EU", l.color_endpoint.unquant_lut, l.color_endpoint.unquant_offset);
   dump("WQ", &l.weights.lut[0][0], sizeof l.weights.lut);
   dump("WU", l.weights.unquant_lut, l.weights.unquant_offset);
   dump("TQ", l.integer.trits_quints, 256 + 128);
   if (g_c) {
      printf("/* SPDX-License-Identifier: MIT. GENERATED by shader/gen-bc-spv.sh (gen-astc-luts.cpp, Mesa/Granite ASTC tables), do not edit. */\n");
      printf("#define MALI_ASTC_LUT_WORDS %u\nstatic const uint32_t astc_lut[MALI_ASTC_LUT_WORDS] = {", g_n);
      for (unsigned i = 0; i < g_n; i++) printf("%s%uu,", i % 16 ? "" : "\n   ", g_tab[i]);
      printf("\n};\n");
   } else
      printf("#define LUT_WORDS %uu\n", g_n);
   return 0;
}
