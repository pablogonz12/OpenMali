"""Generate tests/zink26_table.h: every device extension zink 26.0.8 knows (zink_device_info.py EXTENSIONS), whether it is
required=True, its enable condition(s), the KHR name it was promoted to, and the device commands zink loads for it (vk.xml, plain
<require> blocks only). Usage: gen_zink26.py zink_device_info.py vk.xml > zink26_table.h
The source files are those of the exact Mesa tag mesa-26.0.8 (src/gallium/drivers/zink/zink_device_info.py)."""
import re, sys, xml.etree.ElementTree as ET

src = open(sys.argv[1]).read()
body = src[src.index('EXTENSIONS = ['):]
body = body[:body.index('\n]\n')]
exts = []
for m in re.finditer(r'Extension\("(VK_\w+)"', body):
    nxt = body.find('Extension("', m.end())
    seg = body[m.start(): nxt if nxt > 0 else len(body)]
    cond = re.findall(r'conditions=\[(.*?)\]', seg, re.S)
    cond = " && ".join(re.findall(r'"([^"]+)"', cond[0])) if cond else ""
    exts.append((m.group(1), 'required=True' in seg, cond))

root = ET.parse(sys.argv[2]).getroot()
devtypes = {"VkDevice", "VkQueue", "VkCommandBuffer"}
cmds = {}
for c in root.find('commands').findall('command'):
    if c.get('alias'):
        continue
    p = c.find('param')
    cmds[c.find('proto').find('name').text] = p.find('type').text if p is not None else ""
aliases = {c.get('name'): c.get('alias') for c in root.find('commands').findall('command') if c.get('alias')}
xe = {e.get('name'): e for e in root.find('extensions').findall('extension')}

def dev_cmds(name):
    e = xe.get(name)
    out = []
    if e is None:
        return out
    for r in e.findall('require'):
        if r.get('depends') or r.get('feature') or r.get('extension'):
            continue
        for c in r.findall('command'):
            n = c.get('name')
            real = aliases.get(n, n)
            if cmds.get(real) in devtypes:
                out.append(n)
    return out

print("/* SPDX-License-Identifier: MIT. GENERATED by tests/gen_zink26.py from Mesa mesa-26.0.8 zink_device_info.py + vk.xml; do not edit. */")
print("struct zink26_ext { const char *name, *twin, *cond; int required; const char *const *cmds; unsigned ncmds; };")
for n, r, c in exts:
    cs = dev_cmds(n)
    if cs:
        print("static const char *const zc_%s[] = {%s};" % (n, ", ".join('"vk%s"' % x[2:] for x in cs)))
print("static const struct zink26_ext zink26_exts[] = {")
for n, r, c in exts:
    e = xe.get(n)
    twin = e.get('promotedto', '') if e is not None else ''
    twin = twin if twin.startswith('VK_KHR_') or twin.startswith('VK_EXT_') else ''
    cs = dev_cmds(n)
    print('   {"%s", "%s", "%s", %d, %s, %d},' % (n, twin, c.replace('"', '\\"'), 1 if r else 0, ("zc_" + n) if cs else "NULL", len(cs)))
print("};")
