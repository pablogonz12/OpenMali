"""Generate tests/dxvk_api_table.h from DXVK's src/vulkan/vulkan_loader.h (VULKAN_FN list) and vk.xml.
Each command is tagged with the first owner (core 1.x or extension) and the loader level.
Usage: gen_dxvk_api.py vulkan_loader.h vk.xml > dxvk_api_table.h"""
import re, sys, xml.etree.ElementTree as ET
hdr = open(sys.argv[1]).read()
sec = "lib"; fns = []
for line in hdr.splitlines():
    if re.search(r'struct\s+InstanceFn', line): sec = "instance"
    elif re.search(r'struct\s+DeviceFn', line): sec = "device"
    m = re.search(r'VULKAN_FN\((\w+)\)', line)
    if m and not line.lstrip().startswith("#"): fns.append((m.group(1), sec))
root = ET.parse(sys.argv[2]).getroot()
aliases = {c.get('name'): c.get('alias') for c in root.find('commands').findall('command') if c.get('alias')}
owner = {}
depends = {}   # command -> the require block's `depends` expression (extension/version names, ',' = or, '+' = and)
def take(name, own, dep=None):
    if name not in owner:
        owner[name] = own
        depends[name] = dep or ""
for f in root.findall('feature'):
    if 'vulkan' not in f.get('api').split(','): continue
    for r in f.findall('require'):
        for c in r.findall('command'): take(c.get('name'), f.get('name'))
for e in root.find('extensions').findall('extension'):
    if 'vulkan' not in (e.get('supported') or '').split(','): continue
    for r in e.findall('require'):
        for c in r.findall('command'): take(c.get('name'), e.get('name'), r.get('depends'))
print("/* SPDX-License-Identifier: MIT. GENERATED by tests/gen_dxvk_api.py from DXVK vulkan_loader.h + vk.xml; do not edit. */")
print("struct dxa_fn { const char *name; const char *owner; int level; const char *depends; };  /* level 0 lib, 1 instance, 2 device */")
print("static const struct dxa_fn dxvk_api[] = {")
for n, s in fns:
    o = owner.get(n) or owner.get(aliases.get(n, n)) or "?"
    # an alias (vkFooKHR) may be owned by the promoted core version; keep the name's own owner when it has one
    d = depends.get(n) or depends.get(aliases.get(n, n)) or ""
    print('   {"%s", "%s", %d, "%s"},' % (n, o, {"lib":0,"instance":1,"device":2}[s], d))
print("};")
