"""Generate tests/procaddr_table.h: for every Vulkan 1.0-1.3 core version and every extension of vk.xml, the commands of its
unconditional <require> blocks, tagged device or instance level (first parameter VkInstance/VkPhysicalDevice = instance).
t_angle_seq resolves each through vkGetInstanceProcAddr/vkGetDeviceProcAddr for every advertised extension: a NULL one is a crash
for any caller that fetched the table (ANGLE, zink and volk dereference without checking).
Usage: gen_procaddr.py vk.xml > procaddr_table.h"""
import re, sys, xml.etree.ElementTree as ET

root = ET.parse(sys.argv[1]).getroot()
cmds = {}
for c in root.find('commands').findall('command'):
    if c.get('api') and 'vulkan' not in c.get('api').split(','):
        continue
    if c.get('alias'):
        continue
    p = c.find('param')
    cmds[c.find('proto').find('name').text] = p.find('type').text if p is not None else ""
aliases = {c.get('name'): c.get('alias') for c in root.find('commands').findall('command') if c.get('alias')}
GLOBAL = {"vkCreateInstance", "vkEnumerateInstanceExtensionProperties", "vkEnumerateInstanceLayerProperties", "vkEnumerateInstanceVersion"}

def level(n):
    real = aliases.get(n, n)
    t = cmds.get(real)
    if t is None or real in GLOBAL:
        return None
    return t in ("VkInstance", "VkPhysicalDevice") and "instance" or "device"

def collect(el):
    out, seen = [], set()
    for r in el.findall('require'):
        if r.get('depends') or r.get('feature') or r.get('extension'):
            continue
        if r.get('api') and 'vulkan' not in r.get('api').split(','):
            continue
        for c in r.findall('command'):
            n = c.get('name')
            lv = level(n)
            if lv and n not in seen:
                seen.add(n)
                out.append((n, lv))
    return out

items = []
for f in root.findall('feature'):
    if re.fullmatch(r'VK_(BASE_|COMPUTE_|GRAPHICS_)?VERSION_1_[0-3]', f.get('name')) and 'vulkan' in f.get('api').split(','):
        items.append((f.get('name'), 1, 0, collect(f)))
for e in root.find('extensions').findall('extension'):
    if 'vulkan' not in (e.get('supported') or '').split(','):
        continue
    cs = collect(e)
    if cs:
        items.append((e.get('name'), 0, 1 if e.get('type') == 'instance' else 0, cs))

print("/* SPDX-License-Identifier: MIT. GENERATED by tests/gen_procaddr.py from vk.xml; do not edit. */")
print("struct pa_cmd { const char *name; int device; };")
print("struct pa_ext { const char *name; int core, instance; const struct pa_cmd *cmds; unsigned ncmds; };")
for i, (n, core, inst, cs) in enumerate(items):
    print("static const struct pa_cmd pc_%d[] = {%s};" % (i, ", ".join('{"%s", %d}' % (c, lv == "device") for c, lv in cs)))
print("static const struct pa_ext procaddr_exts[] = {")
for i, (n, core, inst, cs) in enumerate(items):
    print('   {"%s", %d, %d, pc_%d, %d},' % (n, core, inst, i, len(cs)))
print("};")
