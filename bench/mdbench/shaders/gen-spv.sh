#!/bin/bash
# GLSL -> SPIR-V 1.0 (Vulkan 1.0 target). The .spv files are committed; this only needs glslangValidator.
set -e; cd "$(dirname "$0")"
for s in *.vert *.frag *.comp; do glslangValidator -V --target-env vulkan1.0 "$s" -o "$s.spv" >/dev/null; done
# embed all .spv in ../src/spv_embed.h (the app is a single self-contained binary; --spv-dir can still override at run time)
python3 -I - . ../src/spv_embed.h <<'P'
import sys, glob, os
d, out = sys.argv[1], sys.argv[2]
L = ["/* generated by shaders/gen-spv.sh, do not edit */", "#include <stdint.h>", "#include <stddef.h>"]
names = []
for f in sorted(glob.glob(os.path.join(d, "*.spv"))):
    n = os.path.basename(f)[:-4].replace(".", "_")
    b = open(f, "rb").read()
    L.append("static const unsigned char spv_%s[] = {%s};" % (n, ",".join(str(x) for x in b)))
    names.append((os.path.basename(f), n))
L.append("static const struct { const char *name; const unsigned char *data; size_t size; } spv_table[] = {")
for f, n in names: L.append('  {"%s", spv_%s, sizeof spv_%s},' % (f, n, n))
L.append("};")
open(out, "w").write("\n".join(L) + "\n")
P
