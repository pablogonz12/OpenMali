"""Generates cefprof_gen.h from vk.xml: counting/timing wrappers for the device commands below, VkFormat names and
the VkBool32 member names of every feature struct. A wrapper calls hook_<Name>() (after the driver) when
cefprof_layer.c defines it as `H(<Name>)`."""
